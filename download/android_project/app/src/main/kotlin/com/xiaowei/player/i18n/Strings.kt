        "sv", "cs", "hu", "el", "ro", "fi", "da", "nb",
        "ms", "tl"
    )

    private val manualLangState = mutableStateOf<String?>(null)

    val currentLangState = manualLangState

    fun setCurrentLanguage(langCode: String?) {
        manualLangState.value = langCode
    }

    private fun currentLang(): String {

        manualLangState.value?.let { return it }

        val locale = Locale.getDefault()
        val lang = locale.language
        val country = locale.country

        if (lang == "zh") {
            return when (country) {
                "TW" -> "zh-TW"
                "HK" -> "zh-HK"
                "MO" -> "zh-MO"
                else -> "zh"  
            }
        }
        return if (lang in SUPPORTED_LANGS) lang else "en"
    }

    fun get(key: String): String {

        manualLangState.value
        val lang = currentLang()
        val map = ALL_STRINGS[key] ?: return key

        return map[lang] ?: map["zh"] ?: map["en"] ?: key
    }

    fun get(key: String, vararg args: Any): String {
        val template = get(key)
        return formatTemplate(template, args)
    }

    private fun formatTemplate(template: String, args: Array<out Any>): String {
        var result = template
        args.forEachIndexed { index, arg ->

            val placeholder1 = Regex.escape("%" + (index + 1) + "\$s")
            val placeholder2 = Regex.escape("%" + (index + 1) + "\$d")
            result = result.replace(placeholder1.toRegex(), arg.toString())
            result = result.replace(placeholder2.toRegex(), arg.toString())
        }
        return result
    }

