    private val SUPPORTED_LANGS = setOf(
        "zh", "zh-TW", "zh-HK", "zh-MO",
        "en", "ja", "ko", "fr", "de", "es", "ru",
        "pt", "it", "ar", "hi", "th", "vi", "in", "tr",
